export function generateCandles(basePrice: number, count = 40, volatility = 0.015): Candle[] {
  const candles: Candle[] = [];
  let current = basePrice * (1 - volatility * 10);
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    
    const delta = (Math.random() - 0.48) * current * volatility;
    const open = Number(current.toFixed(2));
    const close = Number(Math.max(1, current + delta).toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * current * volatility * 0.7).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * current * volatility * 0.7).toFixed(2));
    const volume = Math.floor(Math.random() * 50000 + 10000);

    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
    });
    current = close;
  }
  return candles;
}

export function generateSparkline(basePrice: number, count = 20, drift = 0): number[] {
  const points: number[] = [basePrice];
  let cur = basePrice;
  for (let i = 1; i < count; i++) {
    const change = (Math.random() - 0.49 + drift * 0.1) * (cur * 0.012);
    cur = Math.max(0.01, cur + change);
    points.push(Number(cur.toFixed(2)));
  }
  return points;
}

